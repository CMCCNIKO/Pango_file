// SFP1 (board signal SFP2) / HSST Channel 2 receive adapter.
//
// The generated Pango IP owns all HSST primitives and reset sequencing.  This
// wrapper only closes the recovered-clock feedback required by the IP and
// presents the small RX-only contract used by the fiber video frontend.
//////////////////////////////////////////////////////////////////////////////////
module fiber_hsst_rx_adapter(
    input          i_free_clk,
    input          i_rst_n,
    input          i_refckn,
    input          i_refckp,
    input          i_rxn,
    input          i_rxp,
    input          i_sfp_los,

    output         o_rx_clk,
    output         o_pll_ready,
    output         o_rx_lane_done,
    output         o_rx_lane_ready,
    output [31:0]  o_rxd,
    output [3:0]   o_rxk,
    output [3:0]   o_decode_error,
    output [3:0]   o_disparity_error,
    output         o_signal_detect,
    output         o_cdr_align,
    output [1:0]   o_watchdog_status
);
    wire hsst_rx_clk;
    wire hsst_pll_done;
    wire hsst_rx_lane_done;
    wire [1:0] unused_watchdog_status;
    wire unused_rx_signal_detect;
    wire unused_cdr_align;
    wire [3:0] unused_rx_disparity_error;
    wire [3:0] unused_rx_decode_error;
    wire [2:0] unused_rx_status;
    wire unused_pll_lock;
    wire link_ready_async;
    reg link_ready_meta /* synthesis syn_preserve = 1 */;
    reg link_ready_sync /* synthesis syn_preserve = 1 */;

    assign o_rx_clk = hsst_rx_clk;
    assign o_pll_ready = hsst_pll_done;
    assign o_rx_lane_done = hsst_rx_lane_done;
    assign o_watchdog_status = unused_watchdog_status;
    assign o_signal_detect = unused_rx_signal_detect;
    assign o_cdr_align = unused_cdr_align;
    assign o_decode_error = unused_rx_decode_error;
    assign o_disparity_error = unused_rx_disparity_error;
    assign link_ready_async = hsst_pll_done && hsst_rx_lane_done && !i_sfp_los;
    assign o_rx_lane_ready = link_ready_sync;

    // PLL/lane-done are generated by the IP reset controller in the free-clock
    // domain and LOS is an asynchronous module input.  Assert not-ready
    // asynchronously, then require two recovered-clock edges before enabling
    // the video frontend.  This prevents an asynchronous status net from
    // becoming a high-fanout clock-enable throughout the RX datapath.
    always @(posedge hsst_rx_clk or negedge link_ready_async) begin
        if (!link_ready_async) begin
            link_ready_meta <= 1'b0;
            link_ready_sync <= 1'b0;
        end else begin
            link_ready_meta <= 1'b1;
            link_ready_sync <= link_ready_meta;
        end
    end

    fiber_hsst_ch0 u_fiber_hsst_ch0(
        .i_free_clk(i_free_clk),
        .i_pll_rst_0(!i_rst_n),
        .i_wtchdg_clr_0(!i_rst_n),
        .o_wtchdg_st_0(unused_watchdog_status),
        .o_pll_done_0(hsst_pll_done),
        .o_rxlane_done_2(hsst_rx_lane_done),
        .i_p_refckn_1(i_refckn),
        .i_p_refckp_1(i_refckp),
        .o_p_clk2core_rx_2(hsst_rx_clk),
        .i_p_rx2_clk_fr_core(hsst_rx_clk),
        .o_p_pll_lock_0(unused_pll_lock),
        .o_p_rx_sigdet_sta_2(unused_rx_signal_detect),
        .o_p_lx_cdr_align_2(unused_cdr_align),
        .i_p_pcs_word_align_en_2(1'b1),
        .i_p_l2rxn(i_rxn),
        .i_p_l2rxp(i_rxp),
        .o_rxstatus_2(unused_rx_status),
        .o_rxd_2(o_rxd),
        .o_rdisper_2(unused_rx_disparity_error),
        .o_rdecer_2(unused_rx_decode_error),
        .o_rxk_2(o_rxk)
    );
endmodule
