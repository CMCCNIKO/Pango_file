`timescale 1ns/1ps

// Ready/valid 3x3 raster window generator for one packed channel group.
// Window packing is row-major with top-left in the least-significant slice.
//
// The two history rows are synchronous one-read/one-write memories. A single
// pending-token register aligns each accepted pixel with the registered RAM
// outputs. Frame-bottom padding is generated by sequentially reading one
// synthetic zero row, avoiding the multi-address flush reads that prevent
// block-RAM inference.
module npu_depthwise_swg_3x3 #(
    parameter integer IMAGE_WIDTH  = 56,
    parameter integer IMAGE_HEIGHT = 42,
    parameter integer LANE_WIDTH   = 8,
    parameter integer CHANNELS     = 8,
    parameter integer COORD_WIDTH  = 16
) (
    input  wire                                           clk,
    input  wire                                           rst_n,

    input  wire                                           in_valid,
    output wire                                           in_ready,
    input  wire [(LANE_WIDTH*CHANNELS)-1:0]              in_data,

    output wire                                           out_valid,
    input  wire                                           out_ready,
    output wire [(LANE_WIDTH*CHANNELS*9)-1:0]            out_window,
    output wire [COORD_WIDTH-1:0]                         out_x,
    output wire [COORD_WIDTH-1:0]                         out_y
);

    function integer address_width;
        input integer depth;
        integer value;
        begin
            address_width = 0;
            value = depth - 1;
            while (value > 0) begin
                address_width = address_width + 1;
                value = value >> 1;
            end
            if (address_width < 1)
                address_width = 1;
        end
    endfunction

    function [COORD_WIDTH-1:0] to_coord;
        input integer value;
        begin
            to_coord = value[COORD_WIDTH-1:0];
        end
    endfunction

    localparam integer PIXEL_WIDTH    = LANE_WIDTH * CHANNELS;
    localparam integer WINDOW_WIDTH   = PIXEL_WIDTH * 9;
    localparam integer LINE_ADDR_WIDTH = address_width(IMAGE_WIDTH);

    localparam [2:0] ST_STREAM         = 3'd0;
    localparam [2:0] ST_FLUSH_ROW      = 3'd1;
    localparam [2:0] ST_FLUSH_SENTINEL = 3'd2;
    localparam [2:0] ST_DRAIN          = 3'd3;

    localparam [PIXEL_WIDTH-1:0] ZERO_PIXEL = {PIXEL_WIDTH{1'b0}};
    localparam [COORD_WIDTH-1:0] COORD_TWO = to_coord(2);
    localparam [COORD_WIDTH-1:0] IMAGE_WIDTH_LAST_COORD =
        to_coord(IMAGE_WIDTH - 1);
    localparam [COORD_WIDTH-1:0] IMAGE_HEIGHT_COORD =
        to_coord(IMAGE_HEIGHT);
    localparam [COORD_WIDTH-1:0] IMAGE_HEIGHT_SENTINEL_COORD =
        to_coord(IMAGE_HEIGHT + 1);

    // These are only two 9-entry history rows. Keeping them in logic avoids
    // spending whole M4Ks on a 1,152-bit scratch structure.
    (* ramstyle = "logic" *) reg [PIXEL_WIDTH-1:0] line_one_mem [0:IMAGE_WIDTH-1];
    (* ramstyle = "logic" *) reg [PIXEL_WIDTH-1:0] line_two_mem [0:IMAGE_WIDTH-1];

    reg [PIXEL_WIDTH-1:0] line_one_read_q;
    reg [PIXEL_WIDTH-1:0] line_two_read_q;

    reg [PIXEL_WIDTH-1:0] top_mid_q;
    reg [PIXEL_WIDTH-1:0] top_right_q;
    reg [PIXEL_WIDTH-1:0] middle_mid_q;
    reg [PIXEL_WIDTH-1:0] middle_right_q;
    reg [PIXEL_WIDTH-1:0] bottom_mid_q;
    reg [PIXEL_WIDTH-1:0] bottom_right_q;

    reg [2:0]             state_q;
    reg [COORD_WIDTH-1:0] input_x_q;
    reg [COORD_WIDTH-1:0] input_y_q;
    reg [COORD_WIDTH-1:0] flush_x_q;

    reg                    token_valid_q;
    reg                    token_write_q;
    reg                    token_sentinel_q;
    reg [PIXEL_WIDTH-1:0]  token_data_q;
    reg [COORD_WIDTH-1:0]  token_x_q;
    reg [COORD_WIDTH-1:0]  token_y_q;

    reg                    out_valid_q;
    reg [WINDOW_WIDTH-1:0] out_window_q;
    reg [COORD_WIDTH-1:0]  out_x_q;
    reg [COORD_WIDTH-1:0]  out_y_q;

    wire                    output_slot_available;
    wire                    token_slot_available;
    wire                    token_commit;
    wire                    request_valid;
    wire                    request_fire;
    wire                    request_write;
    wire                    request_sentinel;
    wire                    request_read;
    wire [PIXEL_WIDTH-1:0]  request_data;
    wire [COORD_WIDTH-1:0]  request_x;
    wire [COORD_WIDTH-1:0]  request_y;

    wire                    ram_read_en;
    wire                    ram_write_en;
    wire [LINE_ADDR_WIDTH-1:0] ram_read_addr;
    wire [LINE_ADDR_WIDTH-1:0] ram_write_addr;

    function [WINDOW_WIDTH-1:0] pack_window;
        input [PIXEL_WIDTH-1:0] p00;
        input [PIXEL_WIDTH-1:0] p01;
        input [PIXEL_WIDTH-1:0] p02;
        input [PIXEL_WIDTH-1:0] p10;
        input [PIXEL_WIDTH-1:0] p11;
        input [PIXEL_WIDTH-1:0] p12;
        input [PIXEL_WIDTH-1:0] p20;
        input [PIXEL_WIDTH-1:0] p21;
        input [PIXEL_WIDTH-1:0] p22;
        begin
            pack_window = {p22, p21, p20,
                           p12, p11, p10,
                           p02, p01, p00};
        end
    endfunction

    assign output_slot_available = (~out_valid_q) | out_ready;
    assign token_slot_available  = (~token_valid_q) | output_slot_available;
    assign token_commit          = token_valid_q & output_slot_available;

    assign request_valid = (state_q == ST_STREAM)         ? in_valid :
                           (state_q == ST_FLUSH_ROW)       ? 1'b1 :
                           (state_q == ST_FLUSH_SENTINEL)  ? 1'b1 :
                                                            1'b0;
    assign request_write = (state_q == ST_STREAM);
    assign request_sentinel = (state_q == ST_FLUSH_SENTINEL);
    assign request_read = request_valid & (~request_sentinel);
    assign request_data = (state_q == ST_STREAM) ? in_data : ZERO_PIXEL;
    assign request_x = (state_q == ST_STREAM)        ? input_x_q :
                       (state_q == ST_FLUSH_ROW)      ? flush_x_q :
                                                       {COORD_WIDTH{1'b0}};
    assign request_y = (state_q == ST_STREAM)        ? input_y_q :
                       (state_q == ST_FLUSH_ROW)      ? IMAGE_HEIGHT_COORD :
                                                       IMAGE_HEIGHT_SENTINEL_COORD;
    assign request_fire = request_valid & token_slot_available;

    assign in_ready = (state_q == ST_STREAM) & token_slot_available;

    assign ram_read_en    = request_fire & request_read;
    assign ram_read_addr  = request_x[LINE_ADDR_WIDTH-1:0];
    assign ram_write_en   = token_commit & token_write_q;
    assign ram_write_addr = token_x_q[LINE_ADDR_WIDTH-1:0];

    assign out_valid  = out_valid_q;
    assign out_window = out_window_q;
    assign out_x      = out_x_q;
    assign out_y      = out_y_q;

    // Synchronous history memories. Nonblocking semantics provide old data
    // when a read and write happen to the same location in one cycle.
    always @(posedge clk) begin
        if (ram_read_en)
            line_one_read_q <= line_one_mem[ram_read_addr];
        if (ram_write_en)
            line_one_mem[ram_write_addr] <= token_data_q;
    end

    always @(posedge clk) begin
        if (ram_read_en)
            line_two_read_q <= line_two_mem[ram_read_addr];
        if (ram_write_en)
            line_two_mem[ram_write_addr] <= line_one_read_q;
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            state_q          <= ST_STREAM;
            input_x_q        <= {COORD_WIDTH{1'b0}};
            input_y_q        <= {COORD_WIDTH{1'b0}};
            flush_x_q        <= {COORD_WIDTH{1'b0}};
            token_valid_q    <= 1'b0;
            token_write_q    <= 1'b0;
            token_sentinel_q <= 1'b0;
            token_data_q     <= ZERO_PIXEL;
            token_x_q        <= {COORD_WIDTH{1'b0}};
            token_y_q        <= {COORD_WIDTH{1'b0}};
            top_mid_q        <= ZERO_PIXEL;
            top_right_q      <= ZERO_PIXEL;
            middle_mid_q     <= ZERO_PIXEL;
            middle_right_q   <= ZERO_PIXEL;
            bottom_mid_q     <= ZERO_PIXEL;
            bottom_right_q   <= ZERO_PIXEL;
            out_valid_q      <= 1'b0;
            out_window_q     <= {WINDOW_WIDTH{1'b0}};
            out_x_q          <= {COORD_WIDTH{1'b0}};
            out_y_q          <= {COORD_WIDTH{1'b0}};
        end else begin
            if (out_valid_q && out_ready)
                out_valid_q <= 1'b0;

            if (token_commit) begin
                if ((token_x_q == {COORD_WIDTH{1'b0}}) &&
                    (token_y_q >= 2)) begin
                    out_valid_q  <= 1'b1;
                    out_window_q <= pack_window(
                        (token_y_q == 2) ? ZERO_PIXEL : top_mid_q,
                        (token_y_q == 2) ? ZERO_PIXEL : top_right_q,
                        ZERO_PIXEL,
                        middle_mid_q,
                        middle_right_q,
                        ZERO_PIXEL,
                        bottom_mid_q,
                        bottom_right_q,
                        ZERO_PIXEL
                    );
                    out_x_q <= IMAGE_WIDTH_LAST_COORD;
                    out_y_q <= token_y_q - COORD_TWO;
                end else if ((token_x_q >= 1) && (token_y_q >= 1)) begin
                    out_valid_q  <= 1'b1;
                    out_window_q <= pack_window(
                        (token_y_q == 1) ? ZERO_PIXEL : top_mid_q,
                        (token_y_q == 1) ? ZERO_PIXEL : top_right_q,
                        (token_y_q == 1) ? ZERO_PIXEL : line_two_read_q,
                        middle_mid_q,
                        middle_right_q,
                        line_one_read_q,
                        bottom_mid_q,
                        bottom_right_q,
                        token_data_q
                    );
                    out_x_q <= token_x_q - 1'b1;
                    out_y_q <= token_y_q - 1'b1;
                end

                if (token_x_q == {COORD_WIDTH{1'b0}}) begin
                    top_mid_q      <= ZERO_PIXEL;
                    top_right_q    <= line_two_read_q;
                    middle_mid_q   <= ZERO_PIXEL;
                    middle_right_q <= line_one_read_q;
                    bottom_mid_q   <= ZERO_PIXEL;
                    bottom_right_q <= token_data_q;
                end else begin
                    top_mid_q      <= top_right_q;
                    top_right_q    <= line_two_read_q;
                    middle_mid_q   <= middle_right_q;
                    middle_right_q <= line_one_read_q;
                    bottom_mid_q   <= bottom_right_q;
                    bottom_right_q <= token_data_q;
                end

                if (token_sentinel_q) begin
                    state_q         <= ST_STREAM;
                    input_x_q       <= {COORD_WIDTH{1'b0}};
                    input_y_q       <= {COORD_WIDTH{1'b0}};
                    flush_x_q       <= {COORD_WIDTH{1'b0}};
                    top_mid_q       <= ZERO_PIXEL;
                    top_right_q     <= ZERO_PIXEL;
                    middle_mid_q    <= ZERO_PIXEL;
                    middle_right_q  <= ZERO_PIXEL;
                    bottom_mid_q    <= ZERO_PIXEL;
                    bottom_right_q  <= ZERO_PIXEL;
                end
            end

            if (request_fire) begin
                token_valid_q    <= 1'b1;
                token_write_q    <= request_write;
                token_sentinel_q <= request_sentinel;
                token_data_q     <= request_data;
                token_x_q        <= request_x;
                token_y_q        <= request_y;

                case (state_q)
                    ST_STREAM: begin
                        if (input_x_q == (IMAGE_WIDTH - 1)) begin
                            input_x_q <= {COORD_WIDTH{1'b0}};
                            if (input_y_q == (IMAGE_HEIGHT - 1)) begin
                                state_q   <= ST_FLUSH_ROW;
                                flush_x_q <= {COORD_WIDTH{1'b0}};
                            end else begin
                                input_y_q <= input_y_q + 1'b1;
                            end
                        end else begin
                            input_x_q <= input_x_q + 1'b1;
                        end
                    end

                    ST_FLUSH_ROW: begin
                        if (flush_x_q == (IMAGE_WIDTH - 1)) begin
                            state_q <= ST_FLUSH_SENTINEL;
                        end else begin
                            flush_x_q <= flush_x_q + 1'b1;
                        end
                    end

                    ST_FLUSH_SENTINEL: begin
                        state_q <= ST_DRAIN;
                    end

                    default: begin
                        state_q <= state_q;
                    end
                endcase
            end else if (token_commit) begin
                token_valid_q <= 1'b0;
            end
        end
    end

endmodule
